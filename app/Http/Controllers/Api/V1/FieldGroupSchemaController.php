<?php

namespace App\Http\Controllers\Api\V1;

use App\Http\Controllers\Controller;
use App\Models\Cpt;
use App\Models\CptDefinition;
use App\Support\ContentLocales;
use Illuminate\Http\Request;
use Illuminate\Support\Collection;
use Illuminate\Support\Str;

class FieldGroupSchemaController extends Controller
{
    public function __invoke(Request $request)
    {
        $groups = Cpt::active()
            ->where('team_id', $request->attributes->get('team_id'))
            ->with('cptDefinitions.subCpts')
            ->orderBy('order')
            ->get();

        if ($request->query('format') === 'typescript') {
            return response($this->typescript($groups), 200, ['Content-Type' => 'text/plain; charset=UTF-8']);
        }

        return response()->json([
            'locales' => ContentLocales::active(),
            'default_locale' => ContentLocales::default(),
            'groups' => $groups->map(fn (Cpt $g) => [
                'slug' => $g->slug,
                'title' => $g->title,
                'description' => $g->description,
                'content_type' => $g->content_type,
                'standalone' => (bool) $g->is_standalone,
                'fields' => $g->cptDefinitions->map(fn (CptDefinition $f) => $this->field($f))->values(),
            ])->values(),
        ]);
    }

    private function field(CptDefinition $f): array
    {
        return [
            'name' => $f->name,
            'label' => $f->label,
            'type' => $f->type,
            'required' => $f->required,
            'translatable' => $f->translatable,
            'options' => $f->options,
            'instructions' => $f->instructions,
            'default_value' => $f->default_value,
            'sub_fields' => $f->subCpts->map(fn (CptDefinition $s) => $this->field($s))->values(),
        ];
    }

    private function typescript(Collection $groups): string
    {
        $out = "// Generated by /api/v1/schema?format=typescript — do not edit.\n\n";
        $union = [];

        foreach ($groups as $g) {
            $name = Str::studly($g->slug).'Data';
            $out .= "export interface {$name} {\n  cpt_entry_id: number | null;\n";

            foreach ($g->cptDefinitions as $f) {
                $out .= "  {$f->name}: ".$this->tsType($f).";\n";
            }

            $out .= "}\n\n";
            $union[] = "  | { group_slug: '{$g->slug}'; section_id: number; order: number; data: {$name} }";
        }

        return $out."export type SectionBlock =\n".implode("\n", $union).";\n";
    }

    private function tsType(CptDefinition $f): string
    {
        return match ($f->type) {
            'number' => 'number | null',
            'checkbox' => 'string[]',
            'relation' => 'number | null',
            'image', 'file' => 'string | { url?: string; [key: string]: unknown } | null',
            'select', 'radio' => $this->union($f),
            'repeater' => 'Array<{ '.$f->subCpts->map(fn ($s) => $s->name.': '.$this->tsType($s))->implode('; ').' }>',
            default => 'string | null',
        };
    }

    private function union(CptDefinition $f): string
    {
        $values = collect($f->options ?? [])->pluck('value')->filter()->map(fn ($v) => "'{$v}'");

        return $values->isEmpty() ? 'string | null' : $values->implode(' | ').' | null';
    }
}